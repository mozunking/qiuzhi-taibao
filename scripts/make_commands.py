def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(os.path.dirname(here), "commands"))
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)

    n = 0
    for slug, name, desc, body in cmds():
        content = ("---\n"
                   f"name: {slug}\n"
                   f"description: {desc}\n"
                   "---\n\n"
                   + body.strip() + "\n")
        p = os.path.join(args.out, slug + ".md")
        with open(p, "w", encoding="utf-8") as f:
            f.write(content)
        n += 1
    print(f"已生成 {n} 个命令文件 → {os.path.abspath(args.out)}")
    return 0


